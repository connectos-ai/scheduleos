#!/usr/bin/env node

import { existsSync, readFileSync, readdirSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const allowedLicenses = new Set(["Apache-2.0", "ISC", "MIT"]);
const ignoredDirectories = new Set([".git", "dist", "node_modules"]);
const copiedSourceMarkerScanIgnore = new Set([
  "LICENSE",
  "scripts/check-licenses.mjs",
  "docs/current-state-audit.md",
  "docs/current-state-audit-addendum-20260721.md",
  "docs/security/licensing-audit.md"
]);

const forbiddenAssetExtensions = new Set([
  ".eot",
  ".gif",
  ".ico",
  ".jpeg",
  ".jpg",
  ".otf",
  ".png",
  ".svg",
  ".ttf",
  ".webp",
  ".woff",
  ".woff2"
]);

const textExtensions = new Set([
  "",
  ".css",
  ".csv",
  ".example",
  ".html",
  ".ics",
  ".js",
  ".json",
  ".md",
  ".mjs",
  ".sql",
  ".ts",
  ".txt",
  ".yml",
  ".yaml"
]);

const copiedSourcePatterns = [
  /SPDX-License-Identifier:/iu,
  /Permission is hereby granted/iu,
  /Copyright \(c\)/iu,
  /copied from/iu,
  /adapted from/iu,
  /forked from/iu,
  /generated by/iu
];

const noticeTriggerPatterns = [
  /requires notice/iu,
  /NOTICE file required/iu,
  /third-party notice/iu
];

const fixtureLikePathPattern =
  /(^|[/._-])(fixture|fixtures|sample|samples|template|templates|example|examples)([/._-]|$)/iu;

const failures = [];
const stats = {
  textFilesScanned: 0,
  fixtureLikeFilesReviewed: 0,
  packageLicensesReviewed: 0
};

checkRootLicense();
checkPackageLockLicenses();
scanReleaseTree(root);
checkNoticeFile();

if (failures.length > 0) {
  console.error("License check failed:");
  for (const failure of failures) {
    console.error(`- ${failure}`);
  }
  process.exit(1);
}

console.log(
  [
    "License check passed:",
    `${stats.packageLicensesReviewed} package-lock licenses reviewed,`,
    `${stats.textFilesScanned} release text files scanned,`,
    `${stats.fixtureLikeFilesReviewed} fixture/template/example-like files reviewed,`,
    "assets, copied-source markers, and NOTICE triggers clean."
  ].join(" ")
);

function checkRootLicense() {
  const packageJson = JSON.parse(
    readFileSync(path.join(root, "package.json"), "utf8")
  );
  if (packageJson.license !== "Apache-2.0") {
    failures.push(
      `package.json license must be Apache-2.0, found '${packageJson.license ?? "(missing)"}'.`
    );
  }

  const licensePath = path.join(root, "LICENSE");
  if (!existsSync(licensePath)) {
    failures.push("Root LICENSE file missing.");
    return;
  }

  const licenseText = readFileSync(licensePath, "utf8");
  if (
    !licenseText.includes("Apache License") ||
    !licenseText.includes("Version 2.0")
  ) {
    failures.push("Root LICENSE file does not look like Apache License 2.0.");
  }
}

function checkPackageLockLicenses() {
  const packageLockPath = path.join(root, "package-lock.json");
  if (!existsSync(packageLockPath)) {
    failures.push("package-lock.json missing; dependency license audit cannot run.");
    return;
  }

  const packageLock = JSON.parse(readFileSync(packageLockPath, "utf8"));
  const packages = packageLock.packages ?? {};

  for (const [packagePath, metadata] of Object.entries(packages)) {
    if (packagePath === "") continue;
    const license = metadata.license;
    stats.packageLicensesReviewed += 1;
    if (!allowedLicenses.has(license)) {
      failures.push(
        `${packagePath} has unsupported license '${license ?? "(missing)"}'.`
      );
    }

    const installedPackageJsonPath = path.join(root, packagePath, "package.json");
    if (existsSync(installedPackageJsonPath)) {
      const installed = JSON.parse(readFileSync(installedPackageJsonPath, "utf8"));
      if (installed.license !== license) {
        failures.push(
          `${packagePath} package-lock license '${license}' does not match installed package license '${installed.license ?? "(missing)"}'.`
        );
      }
    }
  }
}

function scanReleaseTree(directory) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    const relativePath = path.relative(root, fullPath);

    if (entry.isDirectory()) {
      if (!ignoredDirectories.has(entry.name)) {
        scanReleaseTree(fullPath);
      }
      continue;
    }

    if (!entry.isFile()) continue;

    const extension = path.extname(entry.name).toLowerCase();
    if (forbiddenAssetExtensions.has(extension)) {
      failures.push(
        `${relativePath} binary/media/font asset needs explicit license review before release.`
      );
    }

    if (fixtureLikePathPattern.test(relativePath)) {
      stats.fixtureLikeFilesReviewed += 1;
    }

    if (!textExtensions.has(extension)) continue;
    stats.textFilesScanned += 1;
    scanTextFile(fullPath, relativePath);
  }
}

function scanTextFile(fullPath, relativePath) {
  if (copiedSourceMarkerScanIgnore.has(relativePath)) return;

  const text = readFileSync(fullPath, "utf8");
  const lines = text.split(/\r?\n/);
  lines.forEach((line, index) => {
    for (const pattern of copiedSourcePatterns) {
      if (pattern.test(line)) {
        failures.push(
          `${relativePath}:${index + 1} contains copied-source marker '${line.trim()}'.`
        );
      }
    }
  });
}

function checkNoticeFile() {
  const noticePath = path.join(root, "NOTICE");
  const noticeExists = existsSync(noticePath);
  let noticeRequired = false;

  for (const filePath of collectTextFiles(root)) {
    const relativePath = path.relative(root, filePath);
    if (relativePath === "LICENSE" || relativePath === "scripts/check-licenses.mjs") {
      continue;
    }
    const text = readFileSync(filePath, "utf8");
    if (noticeTriggerPatterns.some((pattern) => pattern.test(text))) {
      noticeRequired = true;
      break;
    }
  }

  if (noticeRequired && !noticeExists) {
    failures.push("NOTICE file appears required by release-surface text but is missing.");
  }

  if (noticeExists) {
    const noticeText = readFileSync(noticePath, "utf8").trim();
    if (noticeText.length === 0) {
      failures.push("NOTICE file exists but is empty.");
    }
  }
}

function collectTextFiles(directory) {
  const files = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (!ignoredDirectories.has(entry.name)) {
        files.push(...collectTextFiles(fullPath));
      }
      continue;
    }
    if (entry.isFile() && textExtensions.has(path.extname(entry.name).toLowerCase())) {
      files.push(fullPath);
    }
  }
  return files;
}
